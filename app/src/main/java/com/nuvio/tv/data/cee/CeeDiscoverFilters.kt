/** CEE category and language inventory snapshot carried over from Tizen. */
internal object CeeDiscoverFilters {
    val sortKeys = setOf("desc", "asc", "r_desc", "r_asc", "title_asc", "title_desc",
        "views_desc", "views_asc", "stars_asc", "stars_desc", "rating_desc", "rating_asc")
    internal data class Language(val id: String, val name: String, val movies: Int, val series: Int)

    private val categories by lazy { table(genres).associate { it[2] to it[0] } }
    private val languageNames by lazy { table(languages).associate { it[0] to it[1] } }
    private val inventory by lazy { table(pairs).groupBy { it[0] } }

    val categoryNames get() = categories.keys.toList()
    fun categoryId(name: String?) = categories[name]
    fun languages(category: String?) = inventory[categoryId(category)].orEmpty().map {
        Language(it[1], languageNames.getValue(it[1]), it[2].toIntOrNull() ?: 0, it[3].toIntOrNull() ?: 0)
    }
    fun pageSize(year: Boolean, category: String?, sort: String?) =
        if (!year && (categoryId(category) != null || sort !in setOf("title_asc", "title_desc"))) 30 else 12

    private fun table(text: String) = text.trim().lineSequence().map { it.split('\t') }.toList()

